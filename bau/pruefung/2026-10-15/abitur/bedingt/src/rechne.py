# AS40 Bedingte Wahrscheinlichkeit – neue Zahlen, nachgerechnet (sympy)
from sympy import *
R=lambda s: Rational(s); p=lambda *a: print(*a)
p('2022 A1.7a',R('0.15')/R('0.5'))
p('2023 B4.1c',R('0.20')/R('0.65'),N(R('0.20')/R('0.65'),4))
p('2022 B4i',R('0.012')/R('0.06'),N(R('0.108')/R('0.94'),4))
x=symbols('x'); f=R('0.315')*(R('0.142')-x)/(R('0.315')*(R('0.142')-x)+R('0.685')*R('0.055'))
p('2025 B4e f(0)',N(f.subs(x,0),4),'x',[N(s,4) for s in solve(Eq(f,R('0.4')),x)])
a=symbols('a'); g=R('0.8')*R('0.3')/(R('0.8')*R('0.3')+R('0.2')*(1-a))
p('2026 B4f',N(g.subs(a,R('0.3')),4),N(g.subs(a,R('0.5')),4),simplify(diff(g,a)))
p('2022 B4g',R('0.10'),R('0.12')*R('0.10'))
